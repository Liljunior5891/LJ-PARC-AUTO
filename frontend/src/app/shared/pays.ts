/** Pays propose par defaut a la creation d'une entreprise. */
export const PAYS_PAR_DEFAUT = 'Togo';

/** Options de la liste des pays ; la valeur est le nom du pays. */
export const OPTIONS_PAYS: OptionSelect[] = PAYS.map((p) => ({ valeur: p.nom, libelle: p.nom }));

/**
 * Options des pays, plus la valeur deja enregistree si elle n'est pas dans la
 * liste (saisie libre d'avant) : elle reste visible au lieu d'etre effacee.
 */
export function optionsPays(valeurActuelle?: string | null): OptionSelect[] {
  const v = valeurActuelle?.trim();
  if (!v) return OPTIONS_PAYS;
  const trouve = OPTIONS_PAYS.find((o) => (o.valeur as string).toLowerCase() === v.toLowerCase());
  return trouve ? OPTIONS_PAYS : [{ valeur: v, libelle: v }, ...OPTIONS_PAYS];
}

/** Nom du pays tel qu'il figure dans la liste (casse corrigee), ou la saisie telle quelle. */
export function normaliserPays(valeur?: string | null): string {
  const v = valeur?.trim() ?? '';
  const trouve = PAYS.find((p) => p.nom.toLowerCase() === v.toLowerCase());
  return trouve ? trouve.nom : v;
}
